// Writes src/content/catalog.generated.ts from the mission files. Runs before `dev` and `build`;
// catalog.test.ts fails if the committed file is out of date.
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { buildCatalog } from "../src/content/catalog";
import { MISSIONS } from "../src/content/full";
import { DRILLS } from "../src/content/practice";

const dir = fileURLToPath(new URL("../src/content/missions/", import.meta.url));
const modules: Record<string, Record<string, unknown>> = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith(".ts")).sort()) {
  modules[f] = await import(pathToFileURL(dir + f).href);
}
const catalog = buildCatalog(MISSIONS, modules, DRILLS);
const target = fileURLToPath(new URL("../src/content/catalog.generated.ts", import.meta.url));
writeFileSync(
  target,
  `// Generated by scripts/build-catalog.ts (npm run catalog). Do not edit by hand.\nimport type { Catalog } from "./catalog";\n\nexport const CATALOG: Catalog = ${JSON.stringify(catalog, null, 1)};\n`,
);
console.log(`Catálogo: ${catalog.missions.length} misiones, ${catalog.drills.length} ejercicios, ${Object.keys(catalog.modules).length} mundos → ${target}`);
